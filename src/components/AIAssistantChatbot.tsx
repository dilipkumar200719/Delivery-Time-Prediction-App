import React, { useState, useRef, useEffect } from 'react';
import { useApp } from '../context/AppContext';
import {
  Bot,
  Send,
  X,
  Sparkles,
  MapPin,
  Clock,
  HelpCircle,
  CreditCard,
  Utensils,
  Bike,
  Volume2,
  ChevronDown,
  RotateCcw,
  CheckCircle2,
  MessageSquare
} from 'lucide-react';

interface ChatMessage {
  id: string;
  sender: 'user' | 'assistant';
  text: string;
  timestamp: string;
  quickReplies?: string[];
  actionType?: 'TRACK' | 'ETA' | 'DELAY' | 'PAYMENT' | 'ORDER' | 'RIDER';
}

export const AIAssistantChatbot: React.FC = () => {
  const {
    activeOrder,
    tracking,
    prediction,
    conditions,
    cart,
    selectedCity,
    setActiveTab,
    speakAIInsight,
    ttsEnabled
  } = useApp();

  const [isOpen, setIsOpen] = useState(false);
  const [inputText, setInputText] = useState('');
  const [isTyping, setIsTyping] = useState(false);
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const messagesEndRef = useRef<HTMLDivElement>(null);

  const etaMinutes = tracking?.etaMinutes ?? prediction?.predictedEtaMinutes ?? 28;
  const etaRangeMin = Math.max(12, Math.round(etaMinutes * 0.9));
  const etaRangeMax = Math.max(etaRangeMin + 4, Math.round(etaMinutes * 1.15));
  const remainingDist = tracking?.distanceRemainingKm ?? 2.4;
  const driverSpeed = tracking?.speedKmh ?? 28;
  const restaurantName = activeOrder?.restaurantName || 'Spice Route Kitchen';

  // Initialize greeting with live order state
  useEffect(() => {
    if (messages.length === 0) {
      setMessages([
        {
          id: 'msg-init-1',
          sender: 'assistant',
          text: `👋 Hi! I'm your PredictEats AI Assistant. I'm actively tracking your order from **${restaurantName}** in real-time.\n\n⏱️ Current Estimated Arrival: **${etaRangeMin}–${etaRangeMax} mins**\n📍 Courier distance: **${remainingDist} km remaining**\n\nHow can I help you right now?`,
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          quickReplies: [
            '📍 Track Order',
            '⏱️ Check ETA',
            '🧠 Explain ETA',
            '⚡ Fastest Delivery',
            '🍽️ Recommend Food',
            '⚖️ Compare Biryani',
            '💳 Payment Details',
            '❓ Why Delayed?'
          ]
        }
      ]);
    }
  }, [restaurantName, etaRangeMin, etaRangeMax, remainingDist]);

  // Auto scroll to bottom
  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages, isTyping]);

  const generateAIResponse = (query: string): string => {
    const q = query.toLowerCase();

    // 1. Comparison Queries (e.g. Compare Biryani)
    if (q.includes('compare') || q.includes('comparison') || (q.includes('biryani') && q.includes('which'))) {
      return `📊 **AI RESTAURANT & FOOD COMPARISON (Biryani)**\n\n| Restaurant | Price | Rating | AI Predicted ETA | Popularity |\n|---|---|---|---|---|\n| 🍛 **Spice Route Kitchen** | ₹249 | ⭐ 4.8 | **22–28 min** (Fastest) | 🔥 High |\n| 🥘 **Royal Feast Nawabi** | ₹280 | ⭐ 4.6 | **30–36 min** | ⭐ High |\n| 🍲 **Bawarchi Hub** | ₹210 | ⭐ 4.4 | **25–32 min** (Budget) | 📈 Medium |\n\n💡 **AI Recommendation:** **Spice Route Kitchen** offers the optimal balance of culinary rating (4.8) and fastest delivery ETA (22–28 min) with 92% on-time confidence.`;
    }

    // 2. Fastest Food / Fastest Restaurant
    if (q.includes('fastest') || q.includes('quickest') || q.includes('fast food') || q.includes('soonest')) {
      return `⚡ **FASTEST AI-PREDICTED RESTAURANTS NEAR YOU**\n\n1. 🥗 **Green Harvest Bowls**\n   • ⏱️ AI ETA: **16–22 min** (Dist: 2.2 km • Prep: 8 min)\n   • ⭐ 4.9 • Healthy Bowls & Salads\n\n2. 🍕 **Artisan Crust Pizza Lab**\n   • ⏱️ AI ETA: **20–26 min** (Dist: 2.8 km • Prep: 12 min)\n   • ⭐ 4.9 • Woodfired Pizza\n\n3. 🍛 **Spice Route Kitchen**\n   • ⏱️ AI ETA: **22–28 min** (Dist: 3.4 km • Prep: 14 min)\n   • ⭐ 4.8 • Royal Dum Biryani\n\n*Ranking is generated by combining live kitchen queue telemetry and road speed vectors.*`;
    }

    // 3. Cheapest / Budget Options (e.g. Under ₹300)
    if (q.includes('cheap') || q.includes('budget') || q.includes('under 300') || q.includes('under ₹300') || q.includes('affordable') || q.includes('low price')) {
      return `🏷️ **BEST VALUE & BUDGET OPTIONS (Under ₹300)**\n\n1. 🍔 **Crispy Veggie Crunch Burger** — **₹149** (Smash & Craft)\n   • ⭐ 4.7 • AI ETA: 20–25 min\n\n2. 🥗 **Mediterranean Quinoa Bowl** — **₹229** (Green Harvest)\n   • ⭐ 4.9 • AI ETA: 16–22 min\n\n3. 🍛 **Hyderabadi Mini Dum Biryani** — **₹199** (Spice Route)\n   • ⭐ 4.8 • AI ETA: 22–28 min\n\n✨ *Apply code PRED20 at checkout for an extra ₹40 off!*`;
    }

    // 4. Food Recommendation ("What should I eat?", "Recommend")
    if (q.includes('what should i eat') || q.includes('recommend') || q.includes('suggestion') || q.includes('suggest') || q.includes('best food') || q.includes('popular')) {
      return `🍽️ **AI TOP PICKS NEAR YOU**\n\n1. 🍛 **Royal Chicken Dum Biryani** — *Spice Route Kitchen*\n   • ⭐ 4.9 (2,800+ reviews) • ₹249\n   • 🤖 AI ETA: **22–28 min** • Best Seller\n\n2. 🍕 **Smoked Truffle Burrata Pizza** — *Artisan Crust Pizza Lab*\n   • ⭐ 4.9 • ₹389\n   • 🤖 AI ETA: **20–26 min** • Chef's Special\n\n3. 🍔 **Truffle Melt Double Smash Burger** — *Smash & Craft*\n   • ⭐ 4.8 • ₹279\n   • 🤖 AI ETA: **18–24 min** • High Value\n\n*Would you like me to filter by Vegetarian, Budget, or Fastest ETA?*`;
    }

    // 5. Vegetarian Food
    if (q.includes('veg') || q.includes('vegetarian') || q.includes('pure veg') || q.includes('paneer') || q.includes('salad')) {
      return `🌱 **TOP HIGH-RATED VEGETARIAN SPECIALTIES**\n\n1. 🥗 **Avocado & Roasted Chickpea Power Bowl** (Green Harvest) — ₹249 (⭐ 4.9)\n2. 🍕 **Smoked Peri-Peri Paneer Pizza** (Artisan Crust) — ₹299 (⭐ 4.8)\n3. 🍛 **Shahi Paneer Dum Biryani** (Spice Route) — ₹219 (⭐ 4.7)\n\nAll prepared in dedicated vegetarian sections with 100% tamper-evident sealing.`;
    }

    // 6. Where is my order / Track
    if (q.includes('where is my order') || q.includes('track') || q.includes('location') || q.includes('where')) {
      return `Your order is currently with delivery partner **Rahul Kumar** 🛵.\n\n📍 **Distance remaining:** ${remainingDist} km\n🚦 **Traffic:** ${conditions.trafficLevel} density\n🌦️ **Weather:** ${conditions.weatherCondition.replace('_', ' ')}\n⏱️ **Updated ETA:** ${etaRangeMin}–${etaRangeMax} minutes.\n\nI'll continue using the latest delivery information to estimate your arrival time!`;
    }

    // 7. What is my current ETA / How long / Arrival clock
    if (q.includes('eta') || q.includes('how long') || q.includes('when') || q.includes('time') || q.includes('arrival')) {
      const arrivalClock = new Date(Date.now() + etaMinutes * 60000).toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' });
      return `⏱️ **AI Delivery ETA:** **${etaRangeMin}–${etaRangeMax} minutes** (expected arrival at ~**${arrivalClock}**).\n\n• Prediction Confidence: **${Math.round((prediction?.confidence ?? 0.92) * 100)}% 🟢**\n• On-Time Probability: **91% 🎯**\n• Delay Risk: **${conditions.trafficLevel === 'SEVERE' ? '38%' : conditions.trafficLevel === 'HIGH' ? '24%' : '12%'} ⚠️**\n\nOur multi-signal model recalculates continuously using courier speed (${driverSpeed} km/h) and corridor congestion.`;
    }

    // 8. Why is my order delayed / Why did ETA change / Why did delivery time increase?
    if (q.includes('why') || q.includes('delay') || q.includes('traffic') || q.includes('change') || q.includes('late') || q.includes('increase')) {
      if (conditions.trafficLevel === 'SEVERE' || conditions.trafficLevel === 'HIGH') {
        return `⚠️ **RECALCULATION EXPLANATION:**\n\nYour delivery time increased by **+${conditions.trafficLevel === 'SEVERE' ? '7–9' : '4–5'} minutes** because **traffic congestion intensified** along the primary transit corridor.\n\n• Previous ETA: **${Math.max(10, etaRangeMin - 5)}–${Math.max(14, etaRangeMax - 5)} min**\n• Current Recalculated ETA: **${etaRangeMin}–${etaRangeMax} min**\n• Root Cause: Heavy vehicle volume at main arterial intersections.`;
      }
      if (conditions.weatherCondition === 'HEAVY_RAIN' || conditions.weatherCondition === 'RAIN') {
        return `🌧️ **WEATHER PROTOCOL ENGAGED:**\n\nYour courier is adhering to **monsoon wet-weather safety speeds** (+3–4 min buffer). Traction stability is prioritized to ensure food arrives safely without spills.`;
      }
      return `✅ **CURRENT STATUS: ON SCHEDULE**\n\nYour delivery is advancing smoothly within the predicted **${etaRangeMin}–${etaRangeMax} min** window with 91% on-time probability. Kitchen prep (${conditions.restaurantPrepTime} min) and pickup synchronization completed without bottleneck.`;
    }

    // 9. Payment details / Did I pay / Transaction ID
    if (q.includes('payment') || q.includes('pay') || q.includes('total') || q.includes('price') || q.includes('cost') || q.includes('bill') || q.includes('paid') || q.includes('transaction')) {
      const totalPaid = activeOrder?.totalAmountRupees || 410;
      return `💳 **PAYMENT & TRANSACTION BREAKDOWN**\n\n• Food Subtotal: ₹${Math.max(100, totalPaid - 40)}\n• Delivery Partner Fee: ₹30\n• Platform & Packaging: ₹10\n• AI Smart Discount: -₹40\n\n**TOTAL PAID: ₹${totalPaid}**\n\n✅ **Status:** PAYMENT SUCCESSFUL\n• Method: **UPI (Google Pay / PhonePe)**\n• Transaction ID: **PE-${activeOrder?.id?.slice(0, 6).toUpperCase() || '784920'}**\n• Order Ref: **#${activeOrder?.id || 'ORD-8553'}**\n• Guaranteed SLA Refund Eligible: **Yes**`;
    }

    // 10. OTP / Delivery Verification
    if (q.includes('otp') || q.includes('pin') || q.includes('verify') || q.includes('verification') || q.includes('code')) {
      return `🔐 **DELIVERY VERIFICATION PIN / OTP**\n\nYour secure doorstep handover PIN is: **8553**\n\nShare this 4-digit code with courier **Rahul Kumar** upon arrival to complete contactless verification.`;
    }

    // 11. Order details / What did I order
    if (q.includes('order details') || q.includes('what did i order') || q.includes('food') || q.includes('items') || q.includes('dish') || q.includes('my order')) {
      const itemsList = activeOrder?.items?.map(i => `• **${i.name}** × ${i.quantity} (₹${i.price * i.quantity})`).join('\n') ||
        `• **Royal Chicken Dum Biryani** × 1 (₹249)\n• **Smoked Peri-Peri Paneer Pizza** × 1 (₹299)`;
      return `🍔 **ACTIVE ORDER SUMMARY**\n\n🏪 Restaurant: **${restaurantName}**\n📦 Order ID: **#${activeOrder?.id || 'ORD-8553'}**\n\n**Items:**\n${itemsList}\n\n📍 Handover to: **Indiranagar, ${selectedCity}**\n🛵 Live Status: **Out for Delivery (${etaRangeMin}–${etaRangeMax} min)**`;
    }

    // 12. Rider status / Where is courier / Rahul
    if (q.includes('rider') || q.includes('driver') || q.includes('courier') || q.includes('partner') || q.includes('rahul') || q.includes('distance')) {
      return `🛵 **COURIER TELEMETRY**\n\n• Delivery Partner: **Rahul Kumar** (⭐ 4.8 • 1,420+ deliveries)\n• Vehicle: **Ather EV 450X**\n• Live Speed: **${driverSpeed} km/h**\n• Remaining Distance: **${remainingDist} km**\n• Temperature Bag: **Insulated & Sealed**\n• Estimated Doorstep Arrival: **~${etaRangeMin} min**`;
    }

    // 13. Kitchen preparation status
    if (q.includes('kitchen') || q.includes('prepare') || q.includes('chef') || q.includes('ready')) {
      return `👨‍🍳 **KITCHEN PREPARATION REPORT**\n\n• Restaurant: **${restaurantName}**\n• Preparation Duration: **${conditions.restaurantPrepTime || 12} minutes**\n• Food Packaging: Tamper-proof thermal bag\n• Handover State: Food is packed and en route with Rahul.`;
    }

    // 14. Explain ETA / How was prediction calculated
    if (q.includes('explain') || q.includes('how was') || q.includes('factors') || q.includes('model') || q.includes('calculation')) {
      return `🧠 **PREDICTEATS AI PREDICTION DECOMPOSITION**\n\n1. 👨‍🍳 **Food Preparation:** ${conditions.restaurantPrepTime || 12} min (Kitchen model)\n2. 🛵 **Rider Pickup & Dispatch:** 4 min (Courier sync)\n3. 📍 **Road Transit Time:** 9 min (${remainingDist} km route)\n4. 🚦 **Traffic Adjustment:** +${conditions.trafficLevel === 'SEVERE' ? '8' : conditions.trafficLevel === 'HIGH' ? '5' : '2'} min (${conditions.trafficLevel})\n5. 🌦️ **Weather Impact:** +${conditions.weatherCondition === 'CLEAR' ? '0' : '3'} min (${conditions.weatherCondition.replace('_', ' ')})\n\n🎯 **Final Predicted Range:** **${etaRangeMin}–${etaRangeMax} min** with **${Math.round((prediction?.confidence ?? 0.92) * 100)}% Confidence**.`;
    }

    // Generic helpful fallback
    return `I understand you're asking about "${query}". Your order is advancing smoothly with current ETA of **${etaRangeMin}–${etaRangeMax} min** from **${restaurantName}**.\n\nYou can ask me about live courier location, ETA breakdowns, payment receipts, food recommendations, or restaurant comparisons!`;
  };

  const handleSendMessage = (textToSend?: string) => {
    const text = (textToSend || inputText).trim();
    if (!text) return;

    const userMsg: ChatMessage = {
      id: `user-${Date.now()}`,
      sender: 'user',
      text,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
    };

    setMessages(prev => [...prev, userMsg]);
    setInputText('');
    setIsTyping(true);

    setTimeout(() => {
      const responseText = generateAIResponse(text);
      const aiMsg: ChatMessage = {
        id: `ai-${Date.now()}`,
        sender: 'assistant',
        text: responseText,
        timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
        quickReplies: [
          '📍 Track Order',
          '⏱️ Check ETA',
          '🧠 Explain ETA',
          '⚡ Fastest Delivery',
          '🍽️ Recommend Food',
          '⚖️ Compare Biryani',
          '💳 Payment Details',
          '❓ Why Delayed?'
        ]
      };
      setMessages(prev => [...prev, aiMsg]);
      setIsTyping(false);

      if (ttsEnabled) {
        speakAIInsight(responseText.replace(/[*•#]/g, ''));
      }
    }, 600);
  };

  return (
    <>
      {/* Floating Launcher Button with Ping Status Badge */}
      <div className="fixed bottom-5 right-5 z-40">
        {!isOpen && (
          <button
            id="btn-open-ai-chatbot"
            onClick={() => setIsOpen(true)}
            className="group relative flex items-center gap-2.5 rounded-full bg-gradient-to-tr from-cyan-600 via-cyan-500 to-blue-600 text-white px-4 py-3 shadow-lg shadow-cyan-600/30 hover:scale-105 hover:shadow-xl transition-all"
          >
            <div className="relative">
              <Bot className="h-5 w-5 animate-bounce" />
              <span className="absolute -top-1 -right-1 flex h-2.5 w-2.5">
                <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-emerald-400 opacity-75" />
                <span className="relative inline-flex rounded-full h-2.5 w-2.5 bg-emerald-500" />
              </span>
            </div>
            <span className="text-xs font-black tracking-wide pr-1">
              Ask AI Assistant
            </span>
            <span className="rounded-full bg-white/20 px-2 py-0.5 text-[10px] font-bold font-mono">
              {etaRangeMin}–{etaRangeMax}m
            </span>
          </button>
        )}
      </div>

      {/* Expandable Chat Window */}
      {isOpen && (
        <div className="fixed bottom-5 right-5 z-50 w-[92vw] sm:w-[420px] h-[580px] max-h-[85vh] rounded-3xl border border-cyan-200 bg-white shadow-2xl flex flex-col overflow-hidden animate-in zoom-in-95 duration-200">
          
          {/* Header */}
          <div className="bg-gradient-to-r from-slate-950 via-cyan-950 to-slate-900 text-white p-4 flex items-center justify-between shadow-md">
            <div className="flex items-center gap-3">
              <div className="relative flex h-10 w-10 items-center justify-center rounded-2xl bg-cyan-600 text-white shadow-sm">
                <Bot className="h-6 w-6" />
                <span className="absolute -bottom-0.5 -right-0.5 h-3 w-3 rounded-full bg-emerald-500 border-2 border-slate-950" />
              </div>
              <div>
                <div className="flex items-center gap-2">
                  <h3 className="text-sm font-black tracking-tight">PredictEats AI Assistant</h3>
                  <span className="rounded-md bg-cyan-500/20 px-1.5 py-0.2 text-[9px] font-mono text-cyan-300 border border-cyan-400/30">
                    ONLINE
                  </span>
                </div>
                <p className="text-[11px] text-slate-300">
                  Connected to Order #{activeOrder?.id || 'ORD-8553'} • {etaRangeMin}–{etaRangeMax}m ETA
                </p>
              </div>
            </div>

            <div className="flex items-center gap-1">
              <button
                onClick={() => setIsOpen(false)}
                className="rounded-lg p-1.5 text-slate-300 hover:text-white hover:bg-white/10 transition-colors"
                title="Minimize chat"
              >
                <ChevronDown className="h-5 w-5" />
              </button>
              <button
                onClick={() => setIsOpen(false)}
                className="rounded-lg p-1.5 text-slate-300 hover:text-white hover:bg-white/10 transition-colors"
                title="Close chat"
              >
                <X className="h-5 w-5" />
              </button>
            </div>
          </div>

          {/* Messages Container */}
          <div className="flex-1 overflow-y-auto p-4 space-y-3.5 bg-slate-50/60 text-xs">
            {messages.map((m) => (
              <div
                key={m.id}
                className={`flex flex-col ${m.sender === 'user' ? 'items-end' : 'items-start'}`}
              >
                <div
                  className={`max-w-[85%] rounded-2xl px-4 py-3 shadow-xs leading-relaxed whitespace-pre-line ${
                    m.sender === 'user'
                      ? 'bg-cyan-600 text-white rounded-br-xs font-medium'
                      : 'bg-white text-slate-800 border border-slate-200/80 rounded-bl-xs'
                  }`}
                >
                  {m.text}
                </div>
                <span className="text-[10px] text-slate-400 mt-1 px-1">
                  {m.timestamp}
                </span>

                {/* Quick replies */}
                {m.quickReplies && (
                  <div className="flex flex-wrap gap-1.5 mt-2 max-w-full">
                    {m.quickReplies.map((qr, idx) => (
                      <button
                        key={idx}
                        onClick={() => handleSendMessage(qr)}
                        className="rounded-xl border border-cyan-200 bg-white hover:bg-cyan-50 px-2.5 py-1 text-[11px] font-bold text-cyan-900 shadow-2xs transition-colors"
                      >
                        {qr}
                      </button>
                    ))}
                  </div>
                )}
              </div>
            ))}

            {isTyping && (
              <div className="flex items-center gap-1.5 text-slate-400 bg-white border border-slate-200 rounded-2xl px-4 py-2.5 w-fit shadow-xs">
                <Sparkles className="h-3.5 w-3.5 text-cyan-600 animate-spin" />
                <span className="text-[11px] font-medium">PredictEats AI is analyzing telemetry...</span>
              </div>
            )}
            <div ref={messagesEndRef} />
          </div>

          {/* Quick Action Bar */}
          <div className="border-t border-slate-100 bg-white px-3 py-2 flex items-center gap-1.5 overflow-x-auto no-scrollbar">
            <button
              onClick={() => handleSendMessage('Track Order')}
              className="flex items-center gap-1 shrink-0 rounded-lg bg-slate-100 hover:bg-slate-200 px-2 py-1 text-[10px] font-bold text-slate-700 transition-colors"
            >
              <MapPin className="h-3 w-3 text-cyan-600" />
              <span>Track</span>
            </button>
            <button
              onClick={() => handleSendMessage('Check ETA')}
              className="flex items-center gap-1 shrink-0 rounded-lg bg-slate-100 hover:bg-slate-200 px-2 py-1 text-[10px] font-bold text-slate-700 transition-colors"
            >
              <Clock className="h-3 w-3 text-amber-600" />
              <span>ETA</span>
            </button>
            <button
              onClick={() => handleSendMessage('Why Delayed?')}
              className="flex items-center gap-1 shrink-0 rounded-lg bg-slate-100 hover:bg-slate-200 px-2 py-1 text-[10px] font-bold text-slate-700 transition-colors"
            >
              <HelpCircle className="h-3 w-3 text-rose-600" />
              <span>Why Delayed?</span>
            </button>
            <button
              onClick={() => handleSendMessage('Payment Details')}
              className="flex items-center gap-1 shrink-0 rounded-lg bg-slate-100 hover:bg-slate-200 px-2 py-1 text-[10px] font-bold text-slate-700 transition-colors"
            >
              <CreditCard className="h-3 w-3 text-emerald-600" />
              <span>Payment</span>
            </button>
            <button
              onClick={() => handleSendMessage('Order Details')}
              className="flex items-center gap-1 shrink-0 rounded-lg bg-slate-100 hover:bg-slate-200 px-2 py-1 text-[10px] font-bold text-slate-700 transition-colors"
            >
              <Utensils className="h-3 w-3 text-purple-600" />
              <span>Items</span>
            </button>
          </div>

          {/* Input Box */}
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage();
            }}
            className="p-3 bg-white border-t border-slate-100 flex items-center gap-2"
          >
            <input
              type="text"
              value={inputText}
              onChange={(e) => setInputText(e.target.value)}
              placeholder="Ask anything about your delivery..."
              className="flex-1 rounded-xl border border-slate-200 bg-slate-50 px-3.5 py-2 text-xs text-slate-900 placeholder:text-slate-400 focus:outline-hidden focus:ring-2 focus:ring-cyan-500/20 focus:border-cyan-500 focus:bg-white transition-all"
            />
            <button
              type="submit"
              disabled={!inputText.trim()}
              className="rounded-xl bg-cyan-600 hover:bg-cyan-700 disabled:opacity-40 text-white p-2 text-xs font-bold transition-colors shadow-xs"
            >
              <Send className="h-4 w-4" />
            </button>
          </form>

        </div>
      )}
    </>
  );
};
